export function getStoredFaculty(): FacultyMember[] {
  try {
    if (typeof window !== 'undefined' && window.localStorage) {
      const data = localStorage.getItem('kjit_faculty_list');
      if (data) {
        const parsed = JSON.parse(data);
        if (Array.isArray(parsed) && parsed.length > 0) {
          return parsed;
        }
      }
    }
  } catch (e) {
    console.error('Failed to read stored faculty:', e);
  }
  return KJIT_FACULTY;
}

export function saveStoredFaculty(list: FacultyMember[]): void {
  try {
    if (typeof window !== 'undefined' && window.localStorage) {
      localStorage.setItem('kjit_faculty_list', JSON.stringify(list));
      window.dispatchEvent(new CustomEvent('kjit_faculty_updated', { detail: list }));
    }
  } catch (e) {
    console.error('Failed to save stored faculty:', e);
  }
}
